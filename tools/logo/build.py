#!/usr/bin/env python3
"""Build Tare's logo: launcher icon layers, the animated splash icon and brand SVGs.

The mark is ▸0◂, the "settled at zero" sign on a scale's display, drawn around the
Instrument Serif zero. Glyphs come from the app's own fonts in ``app/src/main/res/font``
and are written as outlines, so nothing depends on a font being installed.

Usage (from the repository root)::

    pip install fonttools
    python tools/logo/build.py

Writes:

- ``app/src/main/res/drawable/ic_launcher_foreground.xml``: the mark on coral
  (the background colour is ``tare_launcher_background``).
- ``app/src/main/res/drawable/ic_launcher_monochrome.xml``: for themed icons.
- ``app/src/main/res/drawable/ic_splash_animated.xml``: the triangles slide onto the zero.
  Its static state has them slightly apart, so a splash that doesn't animate still shows
  the mark.
- ``docs/brand/*.svg``: icon, mark and wordmark for light and dark backgrounds.

All geometry lives on the 108-unit adaptive-icon canvas, centred on 54,54. The mark stays
inside the 66-unit safe zone.
"""
from __future__ import annotations

import math
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "app/src/main/res/font"
DRAWABLE = ROOT / "app/src/main/res/drawable"
BRAND = ROOT / "docs/brand"

CORAL = "#FF7A50"
CORAL_LIGHT = "#EC5B2C"
ON_CORAL = "#1A0A04"
INK = "#F4F1EC"
INK_LIGHT = "#1B1A18"
DARK_BG = "#0E0D0C"
LIGHT_BG = "#F6F4F0"

# The zero: Instrument Serif "0" at 56 units, centred on the canvas.
ZERO_SIZE = 56
# The triangles: width, height, gap to the zero and the stroke that rounds their corners.
TRI_W, TRI_H, TRI_GAP, TRI_ROUND = 9.5, 15.0, 4.5, 2.4
# The splash starts with the triangles this far out, then slides them in.
SPLASH_OFFSET = 7.0

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/logo/build.py; edit that, not this file. -->\n'


class Font:
    def __init__(self, path: Path):
        self.font = TTFont(path)
        self.glyphs = self.font.getGlyphSet()
        self.cmap = self.font.getBestCmap()

    def glyph(self, ch: str):
        return self.glyphs[self.cmap[ord(ch)]]

    def path(self, ch: str) -> str:
        pen = SVGPathPen(self.glyphs, ntos=lambda v: f"{v:g}")
        self.glyph(ch).draw(pen)
        return pen.getCommands()


SERIF = Font(FONTS / "instrument_serif.ttf")


def zero_placement() -> tuple[float, float, float, float]:
    """Translate and scale for the zero glyph, and its half-width on the canvas."""
    xmin, ymin, xmax, ymax = 36, -9, 424, 730  # glyph bounds in font units
    s = ZERO_SIZE / 1000
    tx = 54 - (xmin + xmax) / 2 * s
    ty = 54 + (ymin + ymax) / 2 * s
    return tx, ty, s, (xmax - xmin) / 2 * s


def triangle(side: int) -> str:
    """One triangle pointing at the zero; side is -1 for the left, 1 for the right."""
    *_, half = zero_placement()
    r = TRI_ROUND / 2
    tip = 54 + side * (half + TRI_GAP)
    base = tip + side * TRI_W
    # The round-join stroke grows the shape by r, so inset the outline to keep the size.
    tip_in, base_in = tip + side * r * 1.6, base - side * r
    hh = TRI_H / 2 - r * 1.3
    return f"M{base_in:.2f},{54 - hh:.2f} L{tip_in:.2f},54 L{base_in:.2f},{54 + hh:.2f} Z"


# --- Android vector drawables ---------------------------------------------------------


def vector_mark(zero_color: str, tri_color: str, names: bool = False, tri_offset: float = 0.0) -> str:
    tx, ty, s, _ = zero_placement()

    def tri(side: int, label: str) -> str:
        name = f' android:name="{label}"' if names else ""
        offset = f' android:translateX="{side * tri_offset:g}"' if tri_offset else ""
        return (
            f"    <group{name}{offset}>\n"
            f'        <path android:pathData="{triangle(side)}"\n'
            f'            android:fillColor="{tri_color}" android:strokeColor="{tri_color}"\n'
            f'            android:strokeWidth="{TRI_ROUND}" android:strokeLineJoin="round" />\n'
            f"    </group>\n"
        )

    return (
        f'    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}"\n'
        f'        android:scaleX="{s:g}" android:scaleY="{-s:g}">\n'
        f'        <path android:fillColor="{zero_color}"\n'
        f'            android:pathData="{SERIF.path("0")}" />\n'
        f"    </group>\n"
        + tri(-1, "left")
        + tri(1, "right")
    )


def vector(body: str, comment: str) -> str:
    return (
        HEADER
        + f"<!-- {comment} -->\n"
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        + body
        + "</vector>\n"
    )


def splash() -> str:
    body = vector_mark("@color/tare_splash_mark", "@color/tare_splash_accent", names=True, tri_offset=SPLASH_OFFSET)
    drawable = (
        '    <aapt:attr name="android:drawable">\n'
        '        <vector android:width="108dp" android:height="108dp"\n'
        '            android:viewportWidth="108" android:viewportHeight="108">\n'
        + "".join("        " + line + "\n" for line in body.rstrip("\n").split("\n"))
        + "        </vector>\n"
        "    </aapt:attr>\n"
    )
    # Hold for a beat so the zero lands first, then slide in with a small overshoot. No
    # startOffset: a delayed animator would show the end state until it starts.
    interpolator = "M0,0 L0.22,0 C0.34,0 0.42,1.1 0.6,1.06 C0.74,1.03 0.86,1 1,1"

    def target(name: str, frm: float) -> str:
        return (
            f'    <target android:name="{name}">\n'
            '        <aapt:attr name="android:animation">\n'
            f'            <objectAnimator android:propertyName="translateX" android:valueFrom="{frm:g}"\n'
            '                android:valueTo="0" android:valueType="floatType" android:duration="700">\n'
            '                <aapt:attr name="android:interpolator">\n'
            f'                    <pathInterpolator android:pathData="{interpolator}" />\n'
            "                </aapt:attr>\n"
            "            </objectAnimator>\n"
            "        </aapt:attr>\n"
            "    </target>\n"
        )

    return (
        HEADER
        + "<!-- Splash icon: the triangles of the mark slide onto the zero, like a scale settling. -->\n"
        '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt">\n'
        + drawable
        + target("left", -SPLASH_OFFSET)
        + target("right", SPLASH_OFFSET)
        + "</animated-vector>\n"
    )


# --- SVG ------------------------------------------------------------------------------


def svg_mark(zero_color: str, tri_color: str) -> str:
    tx, ty, s, _ = zero_placement()
    tris = "".join(
        f'<path d="{triangle(side)}" fill="{tri_color}" stroke="{tri_color}" '
        f'stroke-width="{TRI_ROUND}" stroke-linejoin="round"/>'
        for side in (-1, 1)
    )
    zero = f'<path transform="translate({tx:.3f} {ty:.3f}) scale({s:g} {-s:g})" fill="{zero_color}" d="{SERIF.path("0")}"/>'
    return zero + tris


def squircle(cx: float, cy: float, r: float, n: float = 5.0, steps: int = 96) -> str:
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        pts.append(f"{cx + r * math.copysign(abs(c) ** (2 / n), c):.2f} {cy + r * math.copysign(abs(s) ** (2 / n), s):.2f}")
    return "M" + " L".join(pts) + " Z"


def svg(view: tuple[float, float, float, float], body: str) -> str:
    x, y, w, h = view
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x:g} {y:g} {w:.2f} {h:.2f}">{body}</svg>\n'


def icon_svg(origin: tuple[float, float] = (0, 0)) -> str:
    ox, oy = origin
    return (
        f'<g transform="translate({ox - 18:g} {oy - 18:g})">'
        f'<path d="{squircle(54, 54, 36)}" fill="{CORAL}"/>{svg_mark(ON_CORAL, ON_CORAL)}</g>'
    )


def wordmark(fill: str, size: float = 100) -> tuple[str, float]:
    """'tare' in Instrument Serif, tracked -1% with a little pair kerning; baseline at y=0."""
    kern = {"ta": -6, "ar": -4, "re": 2}
    k, x, out = size / 1000, 0.0, []
    for i, ch in enumerate("tare"):
        out.append(f'<path transform="translate({x:.2f} 0) scale({k:g} {-k:g})" d="{SERIF.path(ch)}"/>')
        adv = SERIF.glyph(ch).width - 10 + kern.get("tare"[i:i + 2], 0)
        x += adv * k
    width = x + 10 * k  # the last letter carries no tracking
    return f'<g fill="{fill}">{"".join(out)}</g>', width


def lockup(fill: str) -> str:
    word, w = wordmark(fill)
    gap = 24
    return svg((-2, -3, 72 + gap + w + 6, 80), icon_svg() + f'<g transform="translate({72 + gap} 64)">{word}</g>')


def main() -> None:
    (DRAWABLE / "ic_launcher_foreground.xml").write_text(
        vector(vector_mark(ON_CORAL, ON_CORAL), "Tare mark: the settled-at-zero sign from a scale's display, around an Instrument Serif zero."),
        encoding="utf-8", newline="\n")
    (DRAWABLE / "ic_launcher_monochrome.xml").write_text(
        vector(vector_mark("#FFFFFFFF", "#FFFFFFFF"), "Themed-icon layer: the launcher tints it."),
        encoding="utf-8", newline="\n")
    (DRAWABLE / "ic_splash_animated.xml").write_text(splash(), encoding="utf-8", newline="\n")

    BRAND.mkdir(parents=True, exist_ok=True)
    files = {
        "icon.svg": svg((0, 0, 72, 72), icon_svg()),
        "mark-on-dark.svg": svg((0, 0, 72, 72), f'<rect width="72" height="72" fill="{DARK_BG}"/><g transform="translate(-18 -18)">{svg_mark(INK, CORAL)}</g>'),
        "mark-on-light.svg": svg((0, 0, 72, 72), f'<rect width="72" height="72" fill="{LIGHT_BG}"/><g transform="translate(-18 -18)">{svg_mark(INK_LIGHT, CORAL_LIGHT)}</g>'),
        "lockup-on-dark.svg": lockup(INK),
        "lockup-on-light.svg": lockup(INK_LIGHT),
    }
    for name, fill in (("wordmark-on-dark.svg", INK), ("wordmark-on-light.svg", INK_LIGHT)):
        word, w = wordmark(fill)
        files[name] = svg((-4, -78, w + 8, 92), word)
    for name, content in files.items():
        (BRAND / name).write_text(content, encoding="utf-8", newline="\n")
    print("wrote", ", ".join(["ic_launcher_foreground.xml", "ic_launcher_monochrome.xml", "ic_splash_animated.xml", *files]))


if __name__ == "__main__":
    main()
